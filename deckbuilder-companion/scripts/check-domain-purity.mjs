#!/usr/bin/env node
/**
 * SPEC-000 Task 6 verification.
 *
 * The domain purity rule is only worth having if it actually fires. This script
 * writes a probe file that deliberately violates both halves of the rule, runs
 * ESLint, and asserts both violations were reported — then deletes the probe.
 *
 * Two ways this rule silently stops working, both of which have already been hit
 * once while writing it:
 *   1. `boundaries/dependencies` inspects only LOCAL imports unless
 *      `checkAllOrigins: true` is set, so the external-module half never fires.
 *   2. `source` / `origin` selectors take a single micromatch string; passing
 *      `{ anyOf: [...] }` makes the matcher throw and the policy is skipped.
 *
 * Both failures are invisible in a normal lint run: it just goes green. Hence
 * this check runs in CI.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const probePath = join(root, "src/domain/model/__purity_probe.ts");

const PROBE = `// Generated by scripts/check-domain-purity.mjs. Deleted automatically.
import React from "react";
import { LegalFooter } from "@/features/legal/LegalFooter";
export const probe = [React, LegalFooter];
`;

/** Each entry must appear in the ESLint output for the check to pass. */
const EXPECTED = [
  {
    label: "external module (react) blocked inside src/domain",
    match: /module source "react".*not allowed in elements of type "domain"/s,
  },
  {
    label: "cross-layer import (domain -> features) blocked",
    match: /from elements of type "domain" to elements of type "features"/,
  },
];

mkdirSync(dirname(probePath), { recursive: true });
writeFileSync(probePath, PROBE);

let output = "";
try {
  execFileSync("npx", ["eslint", "src/domain/model/__purity_probe.ts"], {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
} catch (error) {
  output = `${error.stdout ?? ""}${error.stderr ?? ""}`;
} finally {
  rmSync(probePath, { force: true });
}

const failures = EXPECTED.filter(({ match }) => !match.test(output));

if (failures.length > 0) {
  console.error("✗ Domain purity rule is NOT being enforced.\n");
  for (const { label } of failures) console.error(`  missing: ${label}`);
  console.error("\nESLint output was:\n");
  console.error(output || "  (no output — ESLint reported no problems at all)");
  process.exit(1);
}

console.log("✓ Domain purity rule enforced (external modules + cross-layer imports).");
